CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    kyc_status VARCHAR(20) NOT NULL
);

CREATE TABLE bank_account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holder_name VARCHAR(255) NOT NULL,
    balance DECIMAL(19, 2) NOT NULL,
    account_number VARCHAR(12) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    owner_id BIGINT NOT NULL,
    CONSTRAINT fk_bank_account_owner
        FOREIGN KEY (owner_id) REFERENCES app_user(id)
);

CREATE TABLE account_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(30) NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    timestamp TIMESTAMP NOT NULL,
    reference_number VARCHAR(24) NOT NULL UNIQUE,
    description VARCHAR(255),
    status VARCHAR(20) NOT NULL,
    failure_reason VARCHAR(500),
    account_id BIGINT NOT NULL,
    CONSTRAINT fk_transaction_account
        FOREIGN KEY (account_id) REFERENCES bank_account(account_id)
);

CREATE INDEX idx_bank_account_owner ON bank_account(owner_id);
CREATE INDEX idx_transaction_account_time ON account_transaction(account_id, timestamp);
CREATE INDEX idx_transaction_status ON account_transaction(status);
