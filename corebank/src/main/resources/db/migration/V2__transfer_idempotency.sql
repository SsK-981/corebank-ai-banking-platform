CREATE TABLE transfer_idempotency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    source_account_id BIGINT NOT NULL,
    destination_account_id BIGINT NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    reference_number VARCHAR(19),
    outcome_status VARCHAR(20) NOT NULL,
    failure_message VARCHAR(255),
    source_account_number VARCHAR(12) NOT NULL,
    source_holder_name VARCHAR(255) NOT NULL,
    source_balance DECIMAL(19, 2) NOT NULL,
    masked_recipient_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_transfer_idempotency_owner_key UNIQUE (owner_email, idempotency_key)
);
